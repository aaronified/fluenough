/// The name of an IPA keyboard key in the interface's language, for the
/// long press and for a screen reader (#1221): the IPA's own name for a
/// symbol of the chart, from the ARB (`ipaSymbolXXXX`, the code point in
/// hex), or "Symbol x" for one only a deck uses, which the chart has no name
/// for. A bare glyph is never the name: a screen reader may say nothing for
/// it.
String ipaSymbolName(AppLocalizations l10n, IpaSymbol symbol) =>
    ipaChartName(l10n, symbol.symbol) ?? l10n.ipaSymbolOther(symbol.symbol);

