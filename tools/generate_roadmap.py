#!/usr/bin/env python3
"""Generates wiki/Roadmap.md from GitHub and the plans (#484).

    python3 tools/generate_roadmap.py                  # fetch and rewrite
    python3 tools/generate_roadmap.py --check          # exit 1 if stale
    python3 tools/generate_roadmap.py --fixture F.json # offline, from a recording

The page is fully generated (owner, 2026-10-11: "Roadmap will completely be
auto generated"); a hand edit is overwritten on the next run. docs/ROADMAP.md
stays a pointer to it, because the wiki is the source of truth.

Sources:
  Released                  the GitHub releases, newest first.
  Next releases             the open milestones in version order, each with its
                            approved open issues grouped by label (bug, then
                            enhancement, then the rest), in the order the
                            milestone's description gives (its "#N" mentions).
  Plans                     wiki/Plan-*.md (and any real plan in docs/plans/):
                            title, first "Written" line, "Tracks #N". A plan no
                            issue tracks is flagged (an issue tracks it when the
                            plan says "Tracks #N" or a `plan`-labelled issue
                            names its page).
  Approved, not scheduled   approved open issues with no milestone or in
                            "Any order".

Approved means opened by the owner (their agent posts as the owner), or
labelled `approved`. Issues labelled `from-app` or a mail label stay out until
labelled `approved`, whoever opened them.

The workflow (.github/workflows/roadmap.yml) runs it with GITHUB_TOKEN. The
fixture is {"releases": [...], "milestones": [...], "issues": [...]} in the
REST API's shapes. Standard library only.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "wiki" / "Roadmap.md"
WIKI_URL = "https://github.com/aaronified/fluenough/wiki"
OWNER = "aaronified"
REPO = "aaronified/fluenough"
ANY_ORDER = "any order"
# Labels of reports that are not the owner's own, whoever posted them.
UNTRUSTED = {"from-app", "from-mail", "mail", "feedback-mail"}
HEADER = ("<!-- GENERATED by tools/generate_roadmap.py. Do not edit: "
          "a hand edit is overwritten on the next run. -->")


def labels_of(issue: dict) -> set[str]:
    return {(l["name"] if isinstance(l, dict) else l).lower()
            for l in issue.get("labels", [])}


def is_approved(issue: dict, owner: str = OWNER) -> bool:
    if "pull_request" in issue or issue.get("state", "open") != "open":
        return False
    labels = labels_of(issue)
    if "approved" in labels:
        return True
    if labels & UNTRUSTED:
        return False
    return (issue.get("user") or {}).get("login", "").lower() == owner.lower()


def version_key(title: str) -> tuple:
    nums = re.findall(r"\d+", title)
    return (0, tuple(int(n) for n in nums)) if nums else (1, (), title)


def label_group(issue: dict) -> int:
    labels = labels_of(issue)
    return 0 if "bug" in labels else 1 if "enhancement" in labels else 2


def ordered(issues: list[dict], description: str) -> list[dict]:
    """Bugs, then enhancements, then the rest; within a group, the order of
    the description's #N mentions, then by number."""
    position: dict[int, int] = {}
    for m in re.finditer(r"#(\d+)", description or ""):
        position.setdefault(int(m.group(1)), len(position))
    big = len(position)
    return sorted(issues, key=lambda i: (
        label_group(i), position.get(i["number"], big), i["number"]))


def parse_plan(name: str, text: str) -> dict | None:
    """name is the file stem. None for a pointer ("Moved to the wiki")."""
    lines = text.splitlines()
    title = next((l[2:].strip() for l in lines if l.startswith("# ")), name)
    title = re.sub(r"^Plan:\s*", "", title)
    written = next((l.strip() for l in lines if l.startswith("Written ")), "")
    written = re.sub(r"\s+", " ", written)
    m = re.search(r"Tracks\b(.*?)(?:\n\s*\n|\Z)", text, re.S)
    tracks = sorted({int(n) for n in re.findall(r"#(\d+)", m.group(1))}) if m else []
    return {"name": name, "title": title, "written": written, "tracks": tracks}


def load_plans(root: Path = ROOT) -> list[dict]:
    plans: dict[str, dict] = {}
    for folder, prefix in ((root / "wiki", "Plan-"), (root / "docs" / "plans", "")):
        if not folder.is_dir():
            continue
        for path in sorted(folder.glob(prefix + "*.md")):
            text = path.read_text(encoding="utf-8")
            if "Moved to the wiki" in text[:300]:
                continue
            stem = path.stem
            wiki_name = stem if prefix else "Plan-" + "-".join(
                w.capitalize() for w in stem.split("-"))
            plans.setdefault(wiki_name, parse_plan(wiki_name, text))
    return sorted((p for p in plans.values() if p), key=lambda p: p["name"])


def issue_line(i: dict) -> str:
    return f"- [#{i['number']}]({i.get('html_url') or 'https://github.com/' + REPO + '/issues/' + str(i['number'])}) {i['title']}"


def tracked_by_issues(plan: dict, issues: list[dict]) -> list[int]:
    """Open issues labelled `plan` whose body names the plan's page or file."""
    stem = plan["name"][len("Plan-"):].lower()
    needles = {plan["name"].lower(), f"docs/plans/{stem}.md"}
    return [i["number"] for i in issues if "plan" in labels_of(i)
            and any(n in (i.get("body") or "").lower() for n in needles)]


def render(data: dict, plans: list[dict], owner: str = OWNER) -> str:
    out = [HEADER, "", "# Roadmap", "",
           "Generated from the GitHub releases, milestones and issues, and "
           "from the plans. Do not edit this page: it is rewritten by "
           "`tools/generate_roadmap.py`.", ""]
    issues = [i for i in data.get("issues", []) if is_approved(i, owner)]

    out += ["## Released", ""]
    releases = [r for r in data.get("releases", []) if not r.get("draft")]
    releases.sort(key=lambda r: r.get("published_at") or "", reverse=True)
    if not releases:
        out += ["Nothing released yet.", ""]
    for r in releases:
        tag = r.get("tag_name", "")
        title = (r.get("name") or "").strip()
        out.append(f"- **{tag}**" + (f": {title}" if title and title != tag else ""))
    if releases:
        out.append("")

    out += ["## Next releases", ""]
    miles = [m for m in data.get("milestones", [])
             if m.get("state", "open") == "open" and m["title"].lower() != ANY_ORDER]
    miles.sort(key=lambda m: version_key(m["title"]))
    if not miles:
        out += ["No open milestones.", ""]
    for m in miles:
        mine = [i for i in issues
                if (i.get("milestone") or {}).get("title") == m["title"]]
        out += [f"### {m['title']}", ""]
        out.append(f"{len(mine)} approved open issue{'s' if len(mine) != 1 else ''}.")
        out.append("")
        names = ("Bugs", "Enhancements", "Other")
        for g, label in enumerate(names):
            group = [i for i in ordered(mine, m.get("description") or "")
                     if label_group(i) == g]
            if group:
                out += [f"**{label}**", ""] + [issue_line(i) for i in group] + [""]

    out += ["## Approved, not scheduled", ""]
    loose = [i for i in issues if not i.get("milestone")
             or i["milestone"]["title"].lower() == ANY_ORDER]
    out += [issue_line(i) for i in ordered(loose, "")] or ["None."]
    out.append("")

    out += ["## Plans", ""]
    out += ["A plan with no tracking issue is flagged.", ""]
    for p in plans:
        line = f"- [{p['title']}]({WIKI_URL}/{p['name']})"
        if p["written"]:
            line += f" ({p['written'].split('.')[0].rstrip('.')})"
        tracks = sorted(set(p["tracks"]) | set(tracked_by_issues(p, data.get("issues", []))))
        if tracks:
            line += ", tracks " + ", ".join(f"#{n}" for n in tracks)
        else:
            line += ", **no tracking issue**"
        out.append(line)
    out.append("")
    return "\n".join(out)


def api(path: str, token: str | None) -> list:
    results, page = [], 1
    while True:
        sep = "&" if "?" in path else "?"
        req = urllib.request.Request(
            f"https://api.github.com/repos/{REPO}/{path}{sep}per_page=100&page={page}",
            headers={"Accept": "application/vnd.github+json",
                     **({"Authorization": f"Bearer {token}"} if token else {})})
        with urllib.request.urlopen(req, timeout=60) as r:
            chunk = json.load(r)
        results += chunk
        if len(chunk) < 100:
            return results
        page += 1


def fetch(token: str | None) -> dict:
    return {"releases": api("releases", token),
            "milestones": api("milestones?state=open", token),
            "issues": api("issues?state=open", token)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--fixture")
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args(argv)
    if args.fixture:
        data = json.loads(Path(args.fixture).read_text(encoding="utf-8"))
    else:
        data = fetch(os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN"))
    text = render(data, load_plans())
    out = Path(args.out)
    current = out.read_text(encoding="utf-8") if out.exists() else ""
    if args.check:
        print("Roadmap is current." if current == text else "Roadmap is stale.")
        return 0 if current == text else 1
    if current != text:
        out.write_text(text, encoding="utf-8")
        print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
