"""Write the small golden fixtures the Dart ports are tested against.

Usage: python3 -I golden.py [--out test/fixtures/asr] [--check]

  golden_mel.json   a deterministic 1 s int16 PCM (sine + integer-LCG noise, stored as
                    base64) and a few of its normalised log-mel frames (np_features.py)
  golden_ctc.json   a toy head and encoder output with the greedy ids, confidence and
                    decoded text, plus handcrafted decode cases (ctc.py)

--check regenerates both in memory and exits 1 if the files on disk differ beyond 1e-4
(the unit tests do this). The Dart tests read these files, tolerance 1e-3 for the mel
frames and 1e-4 for the head's logits.
"""
import argparse
import base64
import json
import logging
import math
import os
import sys

import numpy as np

log = logging.getLogger("asr.golden")

if __package__:
    from . import ctc, np_features
else:
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import ctc
    import np_features

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.normpath(os.path.join(HERE, "..", "..", "test", "fixtures", "asr"))
MEL_FRAMES = (0, 1, 2, 50, -1)  # -1 is the last valid frame


def synthetic_pcm(n=16000):
    """int16 samples: 6000 * sin(2 pi 440 t) plus integer LCG noise in [-1000, 1000]."""
    state = 12345
    out = []
    for i in range(n):
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        noise = ((state >> 16) % 2001) - 1000
        v = int(round(6000.0 * math.sin(2.0 * math.pi * 440.0 * i / 16000.0))) + noise
        out.append(max(-32768, min(32767, v)))
    return np.array(out, dtype="<i2")


def golden_mel():
    pcm = synthetic_pcm()
    feats, seq = np_features.log_mel(np_features.pcm16_to_float(pcm))
    idx = [seq - 1 if i == -1 else i for i in MEL_FRAMES]
    return {
        "note": "generated by tools/asr/golden.py; do not edit by hand",
        "sampleRate": np_features.SR, "pcm16leBase64": base64.b64encode(pcm.tobytes()).decode(),
        "samples": int(len(pcm)), "melBins": int(feats.shape[0]), "frames": int(feats.shape[1]),
        "validFrames": int(seq), "frameIndexes": idx,
        "values": [[round(float(v), 6) for v in feats[:, i]] for i in idx],
    }


def _lcg_floats(seed, n):
    state, out = seed, []
    for _ in range(n):
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        out.append(round(((state >> 8) % 2001 - 1000) / 500.0, 3))  # [-2, 2], 3 decimals
    return out


def golden_ctc():
    dim, frames = 4, 10
    pieces = ["<unk>", "▁te", "lu", "gu", "▁x"]  # blank is index 5
    vocab = len(pieces) + 1
    for seed in range(1, 500):
        w = np.array(_lcg_floats(seed, vocab * dim), dtype=np.float32).reshape(vocab, dim)
        b = np.array(_lcg_floats(seed + 7, vocab), dtype=np.float32) * np.float32(0.25)
        enc = np.array(_lcg_floats(seed + 13, dim * frames), dtype=np.float32).reshape(dim, frames)
        head = ctc.Head(w, b, pieces, vocab - 1, "toy")
        ids, conf = head.apply(enc, frames - 1)  # the last frame is padding
        has_repeat = any(a == c != vocab - 1 for a, c in zip(ids, ids[1:]))
        has_blank = (vocab - 1) in ids
        text = ctc.ctc_decode(ids, pieces, vocab - 1)
        if has_repeat and has_blank and len(text) >= 3:
            break
    else:
        raise RuntimeError("no toy seed gives a decode with a repeat, a blank and text")
    blank = vocab - 1
    cases = [[1, 1, blank, 1, 2, 2, blank, blank, 3], [blank, blank], [], [0, 1, 0, 2],
             [4, 3, 3, blank, 3]]
    return {
        "note": "generated by tools/asr/golden.py; do not edit by hand",
        "dim": dim, "vocab": vocab, "blank": blank, "pieces": pieces,
        "weights": w.reshape(-1).tolist(), "bias": b.tolist(),
        "encoderOutput": enc.tolist(), "encoderFrames": frames, "validFrames": frames - 1,
        "logits": [[round(float(v), 5) for v in row] for row in head.logits(enc)[: frames - 1]],
        "ids": ids, "meanConfidence": round(conf, 6), "text": text,
        "decodeCases": [{"ids": c, "text": ctc.ctc_decode(c, pieces, blank)} for c in cases],
    }


def close(a, b, tol=1e-4):
    """Equal as parsed json, floats within tol (libm differences must not fail CI)."""
    if isinstance(a, dict) and isinstance(b, dict):
        return a.keys() == b.keys() and all(close(a[k], b[k], tol) for k in a)
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(close(x, y, tol) for x, y in zip(a, b))
    if isinstance(a, float) or isinstance(b, float):
        return abs(a - b) <= tol
    return a == b


def render(obj):
    return json.dumps(obj, ensure_ascii=False, indent=1) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    try:
        files = {"golden_mel.json": render(golden_mel()), "golden_ctc.json": render(golden_ctc())}
        bad = 0
        for name, text in files.items():
            path = os.path.join(args.out, name)
            if args.check:
                try:
                    with open(path, encoding="utf-8") as f:
                        same = close(json.load(f), json.loads(text))
                except OSError:
                    log.exception("cannot read %s", path)
                    same = False
                if not same:
                    log.error("%s is out of date: run tools/asr/golden.py", path)
                    bad += 1
            else:
                os.makedirs(args.out, exist_ok=True)
                with open(path, "w", encoding="utf-8") as f:
                    f.write(text)
                log.info("wrote %s (%d bytes)", path, len(text.encode()))
        return 1 if bad else 0
    except Exception:
        log.exception("golden failed")
        return 1


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    sys.exit(main())
