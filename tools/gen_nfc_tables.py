#!/usr/bin/env python3
"""Writes lib/core/review/nfc_data.dart: the Unicode data that
`normalizeFixText` (lib/core/review/fix_text.dart) needs to put text in
Normalization Form C, because Dart's core library has no normalisation and
the app takes no package for it (ADR-0058, W1).

Three tables, all from Python's `unicodedata` (Unicode `unicodedata.unidata_version`):
canonical decompositions (fully decomposed, Hangul left to the algorithm),
canonical combining classes, and the primary composites (the pairs that
compose, composition exclusions left out).

Run by hand when the Unicode version changes; the output is committed.
    python3 tools/gen_nfc_tables.py > lib/core/review/nfc_data.dart
"""

import sys
import unicodedata as ud


def main() -> None:
    decomp: list[str] = []
    ccc: list[str] = []
    pairs: list[str] = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
            continue
        ch = chr(cp)
        cls = ud.combining(ch)
        if cls:
            ccc.append(f"{cp:X}:{cls}")
        raw = ud.decomposition(ch)
        if not raw or raw.startswith("<"):
            continue
        full = ud.normalize("NFD", ch)
        if full != ch:
            decomp.append(f"{cp:X}:" + " ".join(f"{ord(c):X}" for c in full))
        parts = raw.split()
        if len(parts) == 2 and ud.normalize("NFC", ch) == ch:
            pairs.append(f"{parts[0]} {parts[1]}:{cp:X}")
    out = sys.stdout
    out.write(f"""// GENERATED by tools/gen_nfc_tables.py from Unicode {ud.unidata_version}.
// Do not edit by hand; rerun the tool. See lib/core/review/fix_text.dart.

// ignore_for_file: lines_longer_than_80_chars
library;

/// Canonical decompositions: `CODEPOINT:FULL DECOMPOSITION`, hex, `;` between
/// entries. Hangul syllables are not listed (the algorithm does them).
const String nfcDecompositions =
    '{";".join(decomp)}';

/// Canonical combining classes of the non-starters: `CODEPOINT:CLASS`.
const String nfcCombiningClasses =
    '{";".join(ccc)}';

/// Primary composites: `FIRST SECOND:COMPOSITE`, hex. Exclusions left out.
const String nfcCompositions =
    '{";".join(pairs)}';
""")


main()
